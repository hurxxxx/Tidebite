using Tidebite.Core;
using Tidebite.Matchmaker;

int passed=0;const string key="test-key-012345678901234567890123456789",other="other-key-012345678901234567890123456789";
long now=1000;
RoomDefinition Room(string id)=>new(){id=id,endpoint="127.0.0.1:7777",key=key};
RoomHeartbeat Heartbeat(int humans=0,int capacity=2,bool accepting=true)=>new(){protocol=OnlineProtocol.Version,humans=humans,capacity=capacity,accepting=accepting};
MatchRequest Request()=>new(){protocol=OnlineProtocol.Version};
void Check(bool value,string label){if(!value)throw new Exception(label);passed++;}
var registry=new RoomRegistry(new[]{Room("one"),Room("two")},()=>now);
Check(registry.Match(Request()).status=="busy","No allocation before heartbeat");
Check(!registry.Heartbeat("one",other,Heartbeat()),"Heartbeat rejects forged key");
Check(!registry.Heartbeat("one",key,Heartbeat(3,2)),"Impossible population rejected");
Check(registry.Heartbeat("one",key,Heartbeat()),"Known heartbeat accepted");
Check(registry.Match(new MatchRequest{protocol=0}).status=="version","Old protocol rejected");
Check(registry.Match(new MatchRequest{protocol=OnlineProtocol.Version,mode="unknown"}).status=="invalid","Unknown mode rejected");
var first=registry.Match(Request());var second=registry.Match(Request());
Check(first.roomId=="one"&&second.roomId=="one"&&first.ticket!=second.ticket,"Distinct tickets pack one room");
Check(registry.Match(Request()).status=="busy","Reservations prevent over-allocation");
Check(!registry.Cancel(first.reservationId,second.ticket),"Cannot cancel another ticket");
Check(registry.Cancel(first.reservationId,first.ticket)&&registry.Cancel(first.reservationId,first.ticket),"Cancellation is idempotent");
var replacement=registry.Match(Request());Check(replacement.status=="assigned","Cancelled seat available");
var gate=new AdmissionGate("one",key);
Check(gate.Admit(replacement.ticket,OnlineProtocol.Version,now,out string nonce)&&nonce==replacement.reservationId,"Assigned ticket admitted");
Check(!gate.Admit(replacement.ticket,OnlineProtocol.Version,now,out _),"Replay rejected");
Check(!new AdmissionGate("two",key).Admit(second.ticket,OnlineProtocol.Version,now,out _),"Wrong room rejected");
Check(!new AdmissionGate("one",other).Admit(second.ticket,OnlineProtocol.Version,now,out _),"Wrong signing key rejected");
Check(!new AdmissionGate("one",key).Admit(second.ticket,0,now,out _),"Wrong protocol rejected");
string tampered=second.ticket.Substring(0,second.ticket.Length-5)+"AAAAA";
Check(!gate.Admit(tampered,OnlineProtocol.Version,now,out _),"Tampering rejected");
Check(!gate.Admit(new string('a',513),OnlineProtocol.Version,now,out _),"Oversized ticket rejected");
Check(!gate.Admit(second.ticket,OnlineProtocol.Version,now+45,out _),"Expired ticket rejected");
Check(!gate.Admit(second.ticket,OnlineProtocol.Version,now-61,out _),"Unbounded future expiry rejected");
var hb=Heartbeat(1);hb.admissions=new[]{replacement.reservationId};registry.Heartbeat("one",key,hb);
Check(registry.Match(Request()).status=="busy","Connected seat counted once, pending seat retained");
registry.Cancel(second.reservationId,second.ticket);Check(registry.Match(Request()).status=="assigned","Consumed reservation is not double counted");
now+=12;Check(registry.Match(Request()).status=="busy","Stale servers excluded");
now+=45;registry.Heartbeat("one",key,Heartbeat());Check(registry.Match(Request()).status=="assigned","Expired unused reservations released");
registry.Heartbeat("one",key,Heartbeat(0,2,false));registry.Heartbeat("two",key,Heartbeat());
Check(registry.Match(Request()).roomId=="two","Joinable round preferred to in-progress round");
now+=100;var concurrent=new RoomRegistry(new[]{Room("one"),Room("two")},()=>now);
concurrent.Heartbeat("one",key,Heartbeat(0,4));concurrent.Heartbeat("two",key,Heartbeat(0,4));
int allocated=0;Parallel.For(0,100,_=>{if(concurrent.Match(Request()).status=="assigned")Interlocked.Increment(ref allocated);});
Check(allocated==8,"Concurrent allocation cannot exceed combined capacity");
Console.WriteLine($"TIDEBITE MATCHMAKER_TESTS passed={passed}");
